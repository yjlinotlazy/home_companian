def render_pose(value: Pose) -> Image.Image:
    image = Image.new("L", (600, 700), 255)
    draw = ImageDraw.Draw(image)
    if value.ground is not None:
        draw.line((30, value.ground, 570, value.ground), fill=120, width=5)
    x, y, radius = value.head
    draw.ellipse((x - radius, y - radius, x + radius, y + radius), outline=0, width=14)
    for stroke in value.strokes:
        draw.line(stroke, fill=0, width=14, joint="curve")
        for point in stroke[1:-1]:
            draw.ellipse(
                (point[0] - 7, point[1] - 7, point[0] + 7, point[1] + 7),
                fill=0,
            )
    return image


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output_dir", type=Path)
    args = parser.parse_args()
    for exercise_id, poses in POSES.items():
        directory = args.output_dir / str(exercise_id)
        directory.mkdir(parents=True, exist_ok=True)
        for number, value in enumerate(poses, 1):
            render_pose(value).save(directory / f"{number}.png", optimize=True)
    print(f"Wrote {len(POSES) * 2} diagrams under {args.output_dir}")


if __name__ == "__main__":
    main()
